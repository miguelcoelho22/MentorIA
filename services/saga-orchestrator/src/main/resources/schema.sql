CREATE TABLE IF NOT EXISTS saga_instances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    essay_id UUID NOT NULL,
    student_id UUID NOT NULL,
    theme TEXT,
    essay_text TEXT,
    status TEXT NOT NULL CHECK (status IN ('STARTED', 'QUOTA_REQUESTED', 'ANALYSIS_REQUESTED', 'FEEDBACK_REQUESTED',
        'CONFIRMING_QUOTA', 'COMPLETED', 'REJECTED', 'COMPENSATING', 'FAILED')),
    failure_reason TEXT,
    failure_detail TEXT,
    deadline TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS saga_instances_status_idx ON saga_instances (status, deadline);

CREATE TABLE IF NOT EXISTS saga_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saga_id BIGINT NOT NULL REFERENCES saga_instances (id),
    step TEXT NOT NULL,
    detail TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS saga_steps_saga_idx ON saga_steps (saga_id, id);
